/*

기능 A — 방향 지시등(Turn signals) 구현
* 핸들 : Potentiometer                  -- o
* 좌측 깜박이: Blue LED                 -- o
* 오른쪽 깜박이: Red LED                -- o
* 왼쪽 방향 레버: SW1 버튼              -- o
* 오른쪽 방향 레버: SW2 버튼            -- o
* 방향 지시 음향 : Buzzer               -- x

* 왼쪽 방향 레버를 누르면 좌측 깜박이가 깜빡이고, Potentiometer로 왼쪽으로 돌렸다가 중앙으로 오면 좌측 깜박이가 커짐
* 오른쪽 방향 레버를 누르면 우측 깜박이가 깜빡이고, Potentiometer로 오른쪽으로 돌렸다가 중앙으로 오면 우측 깜박이가 꺼짐
* 핸들을 반대 방향으로 돌리면 경고음이 울림

---

기능 B — 오토라이트 기능 구현
* 헤드 램프 : RGB LED

* 조도 센서를 이용하여 일정한 밝기 미만이면 자동으로 헤드 램프가켜짐
* ADC를 이용한 조도 센서 제어 기능 개발 필요
* 조도 센서는 channel 6번을 사용함
* 일정한 밝기 이상이면 자동으로 헤드 램프가 꺼짐

* 앞의 기능A와 기능B를 동시에 지원해야 함

*/



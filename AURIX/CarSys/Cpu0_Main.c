void init_Timer_1sec_Interrupt(void) {
    unsigned int currentTime;

    STM0_ICR &= ~((0x1) << CMP0EN);                 // disable compare 0 interrupt

    SRC_STM0_SR0 &= ~((0x1) << SRE);                // disable service request generation

    STM0_CMCON &= ~((0x1) << MSTART0);              // set compare 0 to start counting from STM0_TIM0
    STM0_CMCON |= ((0x1F) << MSIZE0);               // set compare 0 to 32-bit mode

    STM0_ICR &= ~((0x1) << CMP0OS);                 // set compare 0 to one-shot mode

    STM0_ISCR |= ((0x1) << CMP0IRR);                // clear compare 0 interrupt request flag

    currentTime = STM0_TIM0;                        // get current STM0 time

    // STM0_CMP0 = currentTime + (unsigned int)STM0_TICKS_1SEC;
    STM0_CMP0 = currentTime + (unsigned int)STM0_TICKS_HALF_SEC;

    SRC_STM0_SR0 &= ~(STM0_ISR_PRIORITY << SRPN);   // clear service request priority field
    SRC_STM0_SR0 |= (STM0_ISR_PRIORITY << SRPN);    // set service request priority to 

    SRC_STM0_SR0 &= ~(0x3 << TOS);                  // route service request to CPU0 
    SRC_STM0_SR0 |= ((0x1) << SRE);                 // enable service request generation

    STM0_ICR |= ((0x1) << CMP0EN);                  // enable compare 0 interrupt
}

/* 
 * PWM Initialization - GTM TOM0, Channel 11
 * ============================================================ */
void init_GTM_TOM0_PWM(void) {
    // Password Access to unlock CPU0 WDT Control Register 0
    SCU_WDTCPU0CON0 = ((SCU_WDTCPU0CON0 ^ 0xFC) & ~(1 << LCK)) | (1 << ENDINIT);    // clear LCK bit and set ENDINIT bit
    while ((SCU_WDTCPU0CON0 & (1 << LCK)) != 0);    // wait until to unlock CPU0 WDT Control Register 0
    
    // Modify Access to clear the ENDINIT bit in CPU0 WDT Control Register 0
    SCU_WDTCPU0CON0 = ((SCU_WDTCPU0CON0 ^ 0xFC) | (1 << LCK)) & ~(1 << ENDINIT);        // set LCK bit and clear ENDINIT bit
    while ((SCU_WDTCPU0CON0 & (1 << LCK)) == 0);    // wait until to clear the ENDINIT bit in CPU0 WDT Control Register 0

    // Enable GTM module
    GTM_CLC &= ~(1 << DISR);                        // clear DISS bit to enable GTM module

    // Password Access to unlock CPU0 WDT Control Register 0
    SCU_WDTCPU0CON0 = ((SCU_WDTCPU0CON0 ^ 0xFC) & ~(1 << LCK)) | (1 << ENDINIT);    // clear LCK bit and set ENDINIT bit
    while ((SCU_WDTCPU0CON0 & (1 << LCK)) != 0);    // wait until to unlock CPU0 WDT Control Register 0

    // Modify Access to set the ENDINIT bit in CPU0 WDT Control Register 0
    SCU_WDTCPU0CON0 = ((SCU_WDTCPU0CON0 ^ 0xFC) | (1 << LCK)) | (1 << ENDINIT);     // set LCK bit and set ENDINIT bit
    while ((SCU_WDTCPU0CON0 & (1 << LCK)) == 0);    // wait until to set the ENDINIT bit in CPU0 WDT Control Register 0

    while ((GTM_CLC & (1 << DISS)) != 0);           // wait until GTM module is enabled

    // GTM Fixed Clock (FXCLK) Configuration
    GTM_CMU_FXCLK_CTRL &= ~((0xF) << FXCLK_SEL);    // Input clock of CMU_FXCLK     // clear FXCLK_SEL bits to select FXCLK source as PLL1
    GTM_CMU_CLK_EN |= ((0x2) << EN_FXCLK);          // Enable all CMU_FXCLK         // set EN_FXCLK bit to enable FXCLK

    /////////////////////////////////////////////////////////// Buzzer PWM
    // Shadow register 및 Force Update 허용
    GTM_TOM0_TGC1_GLB_CTRL |= ((0x2) << UPEN_CTRL11);   
    GTM_TOM0_TGC1_FUPD_CTRL |= ((0x2) << FUPD_CTRL11);   
    GTM_TOM0_TGC1_FUPD_CTRL |= ((0x2) << RSTCN0_CH11);   

    // CH11 활성화 및 출력 활성화 (0x2 = Enable)
    GTM_TOM0_TGC1_ENDIS_CTRL &= ~((0x3) << ENDIS_CTRL11);
    GTM_TOM0_TGC1_ENDIS_CTRL |= ((0x2) << ENDIS_CTRL11); 
    GTM_TOM0_TGC1_OUTEN_CTRL &= ~((0x3) << OUTEN_CTRL11);
    GTM_TOM0_TGC1_OUTEN_CTRL |= ((0x2) << OUTEN_CTRL11); 

    // CH11 Control 설정 (Active High, FXCLK0 사용)
    GTM_TOM0_CH11_CTRL |= (1 << SL);                 
    GTM_TOM0_CH11_CTRL &= ~((0x7) << CLK_SRC_SR);    
    GTM_TOM0_CH11_CTRL |= ((0x1) << CLK_SRC_SR);     

    // 부저 PWM 주기(음정) 및 듀티비(볼륨) 초기 설정 (약 1kHz)
    GTM_TOM0_CH11_SR0 = 6250;       // 주기 설정 (약 1kHz)                    
    GTM_TOM0_CH11_SR1 = 0;          // 듀티비 설정 (0% 듀티비, 부저 OFF)

    GTM_TOM0_TGC1_GLB_CTRL |= ((0x1) << HOST_TRIG);
}